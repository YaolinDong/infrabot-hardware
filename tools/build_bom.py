"""Write bom.csv and the BOM sections of both READMEs from parts.json.

The README text between the BOM markers is generated; edit this file instead.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = '<!-- BOM:START (generated by tools/build_bom.py) -->', '<!-- BOM:END -->'

# Sub-assemblies in the order of the assembly STEP, with the motor models each one holds.
LINKS = [
    ('baselink', 'Base', '底座', [('J1', 'DM8009P')]),
    ('link1', 'Link 1', '连杆 1', []),
    ('link2', 'Link 2', '连杆 2', [('J2', 'DM8009P'), ('J3', 'DM-J4340P-2EC')]),
    ('link3', 'Link 3', '连杆 3', [('J4', 'DM-J4340P-2EC')]),
    ('link4', 'Link 4', '连杆 4', [('J5', 'DM-J4310-2EC')]),
    ('link5', 'Link 5', '连杆 5', [('J6', 'DM-J4310-2EC')]),
    ('link6', 'Link 6', '连杆 6', [('J7', 'DM-J4310-2EC')]),
    ('link7', 'Link 7', '连杆 7', []),
]
FIELDS = ['item', 'category', 'description', 'location', 'quantity', 'material',
          'envelope_mm', 'mass_each_g', 'file']
TEXT = {
    'en': {
        'title': '## Bill of materials',
        'intro': 'All machined parts are 6061 aluminium. Mass is the CAD volume at 2.70 g/cm³. '
                 'Orange marks the sub-assembly in the arm and dark grey its motors. '
                 'Click a part name to download its STEP file. The same list is in [bom.csv](bom.csv).',
        'summary': '{n} machined piece{s}, {kg:.2f} kg',
        'motors': 'motor models: {m}',
        'head': '| Preview | Part | Qty | Envelope (mm) | Mass (g) |',
        'purchased': '### Purchased parts',
        'phead': '| Part | Model | Qty | Joints | Notes |',
        'motor': 'Joint motor',
        'maker': 'Damiao. Motor models are in the assembly STEP only.',
        'total': 'Machined total: **{n} pieces** of {k} designs, **{kg:.2f} kg**.',
    },
    'zh': {
        'title': '## 物料清单',
        'intro': '机加工零件均为 6061 铝合金。质量按 CAD 体积乘以 2.70 g/cm³ 计算。'
                 '图中橙色为该子装配在整机中的位置，深灰色为其中的电机。'
                 '点击零件名可下载对应 STEP 文件。同样的清单见 [bom.csv](bom.csv)。',
        'summary': '机加工件 {n} 件，{kg:.2f} kg',
        'motors': '电机模型：{m}',
        'head': '| 预览 | 零件 | 数量 | 外形 (mm) | 质量 (g) |',
        'purchased': '### 外购件',
        'phead': '| 名称 | 型号 | 数量 | 关节 | 说明 |',
        'motor': '关节电机',
        'maker': '达妙。电机模型只在整机 STEP 中。',
        'total': '机加工件合计：**{n} 件**，{k} 种设计，**{kg:.2f} kg**。',
    },
}


def load_parts():
    return json.loads((ROOT / 'parts.json').read_text())['parts']


def envelope(p, sep=' × '):
    return sep.join(f'{v:g}' for v in p['envelope_mm'])


def csv_text(parts):
    def cell(value):
        value = str(value)
        return f'"{value}"' if ',' in value else value
    lines = [','.join(FIELDS)]
    for p in parts:
        lines.append(','.join(cell(v) for v in [
            p['id'], 'machined', p['name'], p['link'], p['quantity'], p['material'],
            envelope(p, ' x '), p['mass_g'], p['step']]))
    motors = {}
    for _, _, _, held in LINKS:
        for joint, model in held:
            motors.setdefault(model, []).append(joint)
    for model, joints in motors.items():
        item = 'motor_' + model.lower().replace('-2ec', '').replace('-', '_')
        lines.append(','.join(cell(v) for v in [
            item, 'purchased', f'Damiao {model} joint motor', ', '.join(joints), len(joints),
            '', '', '', '']))
    return '\n'.join(lines) + '\n'


def bom_section(parts, lang):
    t = TEXT[lang]
    lines = [START, '', t['title'], '', t['intro'], '']
    for link, en, zh, held in LINKS:
        own = [p for p in parts if p['link'] == link]
        n = sum(p['quantity'] for p in own)
        kg = sum(p['mass_g'] * p['quantity'] for p in own) / 1000
        summary = t['summary'].format(n=n, s='' if n == 1 else 's', kg=kg)
        if held:
            sep = ', ' if lang == 'en' else '、'
            summary += ' · ' + t['motors'].format(m=sep.join(f'{j} {m}' for j, m in held))
        title = en if lang == 'en' else zh
        alt = f'{en} in the arm' if lang == 'en' else f'{zh}在整机中的位置'
        lines += [f'### {title} · `{link}`', '',
                  f'<img src="docs/images/links/{link}.png" width="360" alt="{alt}">', '',
                  summary, '', t['head'], '|---|---|---|---|---|']
        for p in own:
            name = p['name'] if lang == 'en' else p['name_zh']
            lines.append(f'| <img src="docs/images/parts/{p["id"]}.png" width="120" alt="{name}"> '
                         f'| [{name}]({p["step"]}) | {p["quantity"]} | {envelope(p)} | {p["mass_g"]:g} |')
        lines.append('')
    motors = {}
    for _, _, _, held in LINKS:
        for joint, model in held:
            motors.setdefault(model, []).append(joint)
    lines += [t['purchased'], '', t['phead'], '|---|---|---|---|---|']
    for model, joints in motors.items():
        lines.append(f'| {t["motor"]} | {model} | {len(joints)} | {", ".join(joints)} | {t["maker"]} |')
    lines.append('')
    total = sum(p['mass_g'] * p['quantity'] for p in parts) / 1000
    lines += [t['total'].format(n=sum(p['quantity'] for p in parts), k=len(parts), kg=total), '', END]
    return '\n'.join(lines)


def readmes():
    return {'en': ROOT / 'README.md', 'zh': ROOT / 'README.zh-CN.md'}


def splice(text, section):
    a, b = text.index(START), text.index(END) + len(END)
    return text[:a] + section + text[b:]


def render(root=ROOT):
    """Return the expected bom.csv for the parts.json under root."""
    return csv_text(json.loads((Path(root) / 'parts.json').read_text())['parts'])


def stale_readmes(root=ROOT):
    parts = json.loads((Path(root) / 'parts.json').read_text())['parts']
    out = []
    for lang, name in [('en', 'README.md'), ('zh', 'README.zh-CN.md')]:
        path = Path(root) / name
        if not path.exists():
            continue
        text = path.read_text()
        if START not in text or END not in text or splice(text, bom_section(parts, lang)) != text:
            out.append(name)
    return out


def main():
    parts = load_parts()
    (ROOT / 'bom.csv').write_text(csv_text(parts))
    for lang, path in readmes().items():
        path.write_text(splice(path.read_text(), bom_section(parts, lang)))


if __name__ == '__main__':
    sys.exit(main())
